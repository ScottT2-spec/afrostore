/**
 * shadcn/ui primitives, seeded into every generated project alongside
 * the fixed scaffold and the marketing-section component library.
 *
 * Deliberately NOT the whole shadcn catalog (shadcn ships ~50
 * components) — only the interactive patterns that are genuinely hard
 * for a model to get right unassisted and benefit the most from a
 * proven, accessible, Radix-backed implementation: Dialog, Sheet (the
 * natural fit for a cart drawer or mobile nav), DropdownMenu, Accordion,
 * and Button as the foundational piece the others compose with. Simple
 * presentational sections (Hero, FeatureGrid, etc. in component-library.ts)
 * stay plain hand-written Tailwind — they don't need Radix's compound-
 * component machinery and wrapping them in it would only add complexity
 * for no correctness benefit.
 *
 * These are shadcn's own standard, well-known component implementations
 * (Radix UI + class-variance-authority + the cn() helper from
 * lib/utils.ts) — not custom reinventions — copied in directly the same
 * way shadcn's own CLI would generate them into a real project, since
 * there's no CLI to invoke inside a sandbox file map.
 */

const buttonTsx = `import * as React from "react";
import { Slot } from "@radix-ui/react-slot";
import { cva, type VariantProps } from "class-variance-authority";
import { cn } from "@/lib/utils";

const buttonVariants = cva(
  "inline-flex items-center justify-center gap-2 whitespace-nowrap rounded-[var(--radius)] text-sm font-medium transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-primary focus-visible:ring-offset-2 disabled:pointer-events-none disabled:opacity-50",
  {
    variants: {
      variant: {
        default: "bg-primary text-primary-foreground hover:opacity-90",
        outline: "border border-border bg-background hover:bg-muted",
        ghost: "hover:bg-muted",
        link: "text-primary underline-offset-4 hover:underline",
      },
      size: {
        default: "h-10 px-4 py-2",
        sm: "h-9 px-3",
        lg: "h-11 px-8",
        icon: "h-10 w-10",
      },
    },
    defaultVariants: {
      variant: "default",
      size: "default",
    },
  }
);

export interface ButtonProps
  extends React.ButtonHTMLAttributes<HTMLButtonElement>,
    VariantProps<typeof buttonVariants> {
  asChild?: boolean;
}

const Button = React.forwardRef<HTMLButtonElement, ButtonProps>(
  ({ className, variant, size, asChild = false, ...props }, ref) => {
    const Comp = asChild ? Slot : "button";
    return (
      <Comp className={cn(buttonVariants({ variant, size, className }))} ref={ref} {...props} />
    );
  }
);
Button.displayName = "Button";

export { Button, buttonVariants };
`;

